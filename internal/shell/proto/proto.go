// Package proto is the protocol between `rx edit` and the shell widget that
// started it. The widget answers completion requests using the live shell's
// completion system, so results match what <Tab> would give, with the same
// environment, aliases and settings.
//
// # Contract for a shell widget
//
// Environment: the widget exports RX_HISTFILE (the shell's history file)
// and RX_ALIASES (newline-separated "name=value" lines, each escaped as
// below) to rx.
//
// Transport: the widget creates two fifos in a private (0700) directory,
// starts rx with stdin on one and stdout on the other, opens them itself in
// the same order (the request fifo for writing, then the response fifo for
// reading) and unlinks them. rx must stay in the shell's process group so
// it may read /dev/tty, where it draws the editor. Neither side opens a fifo
// read-write, so rx exiting is seen by the widget as EOF. A widget that
// can't keep descriptors open (fish) may instead run rx as a foreground
// job whose stdout is piped into the widget, with only stdin on a fifo; rx
// then owns the terminal.
//
// Invocation:
//
//	rx edit --shell <name> --cursor N -- BUFFER
//
// N is in the shell's cursor unit (characters or bytes, see shell.Shell);
// the cursor in DONE uses the same unit.
//
// Messages, one per line, fields separated by tabs. Each field is escaped
// with Escape: \ becomes \\, newline \n and tab \t; any other escaped
// character stands for itself. Requests are serial: rx sends one and waits
// for END before sending the next.
//
//	rx → shell   INFO <word> [marker...]
//	shell → rx   I <alias expansion> <completion function> <marker>
//	             END
//	rx → shell   COMPLETE <line>
//	shell → rx   C <value> <description> <group>   (zero or more)
//	             M <message>                       (zero or more)
//	             END
//	rx → shell   DONE <cursor> <line> [run]        (final buffer, rx exits)
//	rx → shell   CANCEL                            (keep original buffer)
//	rx → shell   ERROR <message>                   (keep buffer, show message)
//
// COMPLETE asks for completions with the cursor at the end of line. INFO
// may answer an empty completion function if the shell has none; marker is
// the first of the request's markers found in that function, or empty. rx
// sends the markers of the CLI frameworks it can call directly (e.g.
// cobra's `__complete`). Widgets from before markers answer 1 if the
// function is generated by cobra and 0 otherwise.
//
// Exit: on DONE the widget sets the buffer and cursor, and with the run
// field also runs the command as if the user pressed Enter. Widgets that
// don't know the field ignore it. On CANCEL, ERROR or
// EOF it keeps the original buffer, and for ERROR or EOF shows a short
// message below the prompt. Nothing rx or the widget does may print over
// the prompt.
package proto

import (
	"bufio"
	"context"
	"fmt"
	"io"
	"strings"
	"sync"

	"github.com/amimof/rx/internal/complete"
)

// Client is the rx side of the protocol. It is a complete.Backend for the
// shell's completion system. Requests are serialized because the shell can
// only run one completion at a time.
type Client struct {
	shell string
	mu    sync.Mutex
	r     *bufio.Reader
	w     io.Writer
	err   error
}

// NewClient returns a client for the named shell reading responses from r
// and writing requests to w (rx's stdin and stdout under the widget).
func NewClient(shell string, r io.Reader, w io.Writer) *Client {
	return &Client{shell: shell, r: bufio.NewReader(r), w: w}
}

// Info describes how the shell sees a command word.
type Info struct {
	Alias    string
	CompFunc string
	// Marker is the first of the requested markers found in CompFunc, or
	// "" for none.
	Marker string
}

// legacyCobraMarker is what a widget from before markers means by 1.
const legacyCobraMarker = "__complete"

// Name returns the shell's name, which is also the completion source name.
func (c *Client) Name() string { return c.shell }

func (c *Client) send(fields ...string) error {
	for i := range fields {
		fields[i] = Escape(fields[i])
	}
	_, err := fmt.Fprintln(c.w, strings.Join(fields, "\t"))
	return err
}

// readUntilEnd reads response lines until END, calling fn for each.
func (c *Client) readUntilEnd(fn func(kind string, fields []string)) error {
	for {
		line, err := c.r.ReadString('\n')
		if err != nil {
			return err
		}
		line = strings.TrimSuffix(line, "\n")
		if line == "END" {
			return nil
		}
		parts := strings.Split(line, "\t")
		for i := range parts {
			parts[i] = Unescape(parts[i])
		}
		fn(parts[0], parts[1:])
	}
}

// do runs one request/response exchange. A failed exchange poisons the
// client since the stream position is unknown afterwards.
func (c *Client) do(ctx context.Context, fn func(kind string, fields []string), req ...string) error {
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.err != nil {
		return c.err
	}
	done := make(chan error, 1)
	go func() {
		if err := c.send(req...); err != nil {
			done <- err
			return
		}
		done <- c.readUntilEnd(fn)
	}()
	select {
	case err := <-done:
		c.err = err
		return err
	case <-ctx.Done():
		// The shell is still busy; wait for it so the stream stays in sync,
		// but report the timeout to the caller.
		go func() { <-done }() //nolint:errcheck // only drained, the error is reported below
		c.err = fmt.Errorf("%s completion timed out; backend disabled for this session", c.shell)
		return ctx.Err()
	}
}

// Info asks the shell about a command word, and which of markers its
// completion function contains.
func (c *Client) Info(ctx context.Context, word string, markers ...string) (Info, error) {
	var info Info
	err := c.do(ctx, func(kind string, f []string) {
		if kind == "I" && len(f) >= 3 {
			info = Info{Alias: f[0], CompFunc: f[1], Marker: f[2]}
			switch f[2] {
			case "1":
				info.Marker = legacyCobraMarker
			case "0":
				info.Marker = ""
			}
		}
	}, append([]string{"INFO", word}, markers...)...)
	return info, err
}

// Complete asks the shell to complete req.Line with the cursor at its end.
func (c *Client) Complete(ctx context.Context, req complete.Request) (complete.Result, error) {
	var res complete.Result
	seen := map[string]bool{}
	err := c.do(ctx, func(kind string, f []string) {
		switch kind {
		case "C":
			if len(f) == 0 || seen[f[0]] {
				return
			}
			seen[f[0]] = true
			cand := complete.Candidate{Value: f[0], Source: c.shell}
			if len(f) > 1 {
				cand.Desc = cleanDesc(f[0], f[1])
			}
			if len(f) > 2 {
				cand.Group = f[2]
			}
			res.Candidates = append(res.Candidates, cand)
		case "M":
			if len(f) > 0 {
				if res.Message != "" {
					res.Message += "\n"
				}
				res.Message += f[0]
			}
		}
	}, "COMPLETE", req.Line)
	return res, err
}

// cleanDesc strips the "value  -- " prefix that zsh's _describe puts in
// display strings, leaving just the description.
func cleanDesc(value, d string) string {
	if d == value {
		return ""
	}
	if _, after, ok := strings.Cut(d, " -- "); ok {
		return strings.TrimSpace(after)
	}
	return strings.TrimSpace(strings.TrimPrefix(d, value))
}

// Done sends the final buffer to the shell.
func (c *Client) Done(line string, cursor int) error {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.send("DONE", fmt.Sprint(cursor), line)
}

// Run sends the final buffer to the shell and asks it to run the command.
func (c *Client) Run(line string, cursor int) error {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.send("DONE", fmt.Sprint(cursor), line, "run")
}

// Error tells the shell to keep its original buffer and show msg.
func (c *Client) Error(msg string) error {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.send("ERROR", msg)
}

// Cancel tells the shell to keep its original buffer.
func (c *Client) Cancel() error {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.send("CANCEL")
}

// Escape encodes s as a protocol field.
func Escape(s string) string {
	return strings.NewReplacer(`\`, `\\`, "\n", `\n`, "\t", `\t`).Replace(s)
}

// Unescape reverses Escape.
func Unescape(s string) string {
	if !strings.Contains(s, `\`) {
		return s
	}
	var sb strings.Builder
	for i := 0; i < len(s); i++ {
		if s[i] == '\\' && i+1 < len(s) {
			i++
			switch s[i] {
			case 'n':
				sb.WriteByte('\n')
			case 't':
				sb.WriteByte('\t')
			default:
				sb.WriteByte(s[i])
			}
			continue
		}
		sb.WriteByte(s[i])
	}
	return sb.String()
}

var _ complete.Backend = (*Client)(nil)
